#!/usr/bin/env python3
"""Generate deterministic path indexes without embedding or executing source."""

import ast
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUTS = (
    "docs/high_signal_file_index.json",
    "docs/llm-repo-index.json",
    "docs/codebase-overview.md",
)
ARCHIVAL_DIRS = {"research", "packs", "results"}


def source_paths(root: Path) -> list[str]:
    """Inventory versioned and new, nonignored files in a Git worktree."""
    output = subprocess.check_output(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"], cwd=root
    )
    paths = set(output.decode("utf-8").split("\0")) - {"", *OUTPUTS}
    return sorted(
        path
        for path in paths
        if (root / path).is_file() and (root / path).resolve().is_relative_to(root.resolve())
    )


def file_card(root: Path, path: str) -> dict:
    relative = Path(path)
    top = relative.parts[0]
    exports = []
    dependencies = []
    if top in ARCHIVAL_DIRS:
        layer = "data" if top == "results" else "reference"
        purpose = {
            "results": "Historical benchmark artifact; execution provenance is unverified.",
            "research": "Existing research reference; claims were not reverified in this bootstrap.",
            "packs": "Existing LLM reference pack; no embeddings are generated by this index.",
        }[top]
    elif relative.suffix == ".py":
        layer = "test" if top == "tests" else "tooling" if top == "scripts" else "library"
        tree = ast.parse((root / path).read_text(encoding="utf-8"), filename=path)
        purpose = (ast.get_docstring(tree) or "Python module.").splitlines()[0]
        exports = [
            node.name
            for node in tree.body
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
            and not node.name.startswith("_")
        ]
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module:
                module = Path(*node.module.split("."))
                candidates = [module.with_suffix(".py"), module / "__init__.py"]
                if node.level:
                    candidates = [relative.parent / candidate for candidate in candidates]
                dependencies.extend(
                    str(candidate) for candidate in candidates if (root / candidate).is_file()
                )
    else:
        layer = "docs" if relative.suffix in {".md", ".txt"} else "config"
        purpose = f"Repository {layer}: {relative.name}."
    return {
        "path": path,
        "purpose": purpose,
        "layer": layer,
        "exports": exports,
        "depends_on": sorted(set(dependencies)),
    }


def render_indexes(root: Path) -> dict[str, str]:
    """Return expected content; generated indexes are excluded from their own inputs."""
    cards = [file_card(root, path) for path in source_paths(root)]
    high_signal = [card for card in cards if Path(card["path"]).parts[0] not in ARCHIVAL_DIRS]
    payloads = {
        OUTPUTS[0]: {"schema_version": 1, "files": high_signal},
        OUTPUTS[1]: {"schema_version": 1, "files": cards},
    }
    rendered = {
        path: json.dumps(data, indent=2, ensure_ascii=False) + "\n"
        for path, data in payloads.items()
    }
    lines = [
        "# Codebase overview",
        "",
        "Generated by `python scripts/generate_doc_indexes.py`. Do not edit by hand.",
        "The JSON indexes contain path metadata, public symbols and local imports; no vectors.",
        "Generated indexes exclude themselves to avoid recursive drift.",
        "",
    ]
    for directory in sorted({str(Path(card["path"]).parent) for card in high_signal}):
        lines.extend([f"## `{directory}/`", ""])
        for card in high_signal:
            if str(Path(card["path"]).parent) == directory:
                lines.append(f"- `{card['path']}`: {card['purpose']}")
        lines.append("")
    lines.extend(["## Reference and historical components", ""])
    for directory in sorted(ARCHIVAL_DIRS):
        count = sum(Path(card["path"]).parts[0] == directory for card in cards)
        lines.append(
            f"- `{directory}/`: {count} preserved files; every path is in `llm-repo-index.json`."
        )
    lines.extend(
        [
            "- `templates/`: editable suite starters; their expectations are not execution evidence.",
            "- `inputs/`: optional local fixtures; currently no versioned input files.",
            "",
        ]
    )
    rendered[OUTPUTS[2]] = "\n".join(lines)
    return rendered


def write_indexes(root: Path = ROOT) -> None:
    for path, content in render_indexes(root).items():
        destination = root / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    write_indexes()
    print("Generated 3 nonembedding documentation indexes.")
