#!/usr/bin/env python3
"""
Benchmark Aggregator.
Consolidates benchmark run results across skills into summary markdown tables and JSON manifests.
"""

import sys
import json
from pathlib import Path

def aggregate_results(results_dir: str, output_md: str = None):
    dir_path = Path(results_dir).resolve()
    if not dir_path.exists():
        print(f"Directory {results_dir} does not exist.", file=sys.stderr)
        sys.exit(1)

    benchmark_files = list(dir_path.rglob("*-benchmark.json"))
    if not benchmark_files:
        print(f"No *-benchmark.json files found in {results_dir}")
        return

    table_rows = []
    total_evals = 0
    total_assertions = 0
    total_passed = 0

    for bf in benchmark_files:
        with open(bf, "r", encoding="utf-8") as f:
            d = json.load(f)

        name = d.get("skill_name", bf.stem.replace("-benchmark", ""))
        num_evals = d.get("total_evals", 0)
        num_assertions = d.get("total_assertions", 0)
        passed = d.get("passed_assertions", 0)
        rate = d.get("pass_rate_percent", 0.0)
        duration = d.get("duration_seconds", 0.0)

        total_evals += num_evals
        total_assertions += num_assertions
        total_passed += passed

        status = "✅ PASS" if rate >= 90.0 else "⚠️ WARN" if rate >= 70.0 else "❌ FAIL"
        table_rows.append(f"| `{name}` | {num_evals} | {passed}/{num_assertions} | {rate:.1f}% | {duration}s | {status} |")

    overall_rate = (total_passed / total_assertions * 100) if total_assertions else 0.0

    md = []
    md.append("# Skill Corpus Evaluation Benchmark Results")
    md.append("")
    md.append(f"**Total Skills Evaluated:** {len(benchmark_files)} | **Total Test Cases:** {total_evals} | **Aggregate Pass Rate:** {overall_rate:.1f}%")
    md.append("")
    md.append("| Skill Name | Evals | Assertions Passed | Pass Rate | Duration | Status |")
    md.append("|---|---|---|---|---|---|")
    md.extend(table_rows)
    md.append("")
    md.append("---")
    md.append(f"*Generated by evals benchmark runner on {dir_path.name}*")

    summary_content = "\n".join(md)
    print(summary_content)

    if output_md:
        out_file = Path(output_md)
        with open(out_file, "w", encoding="utf-8") as f:
            f.write(summary_content)
        print(f"\nWrote markdown summary to {output_md}")

if __name__ == "__main__":
    target_dir = sys.argv[1] if len(sys.argv) > 1 else "results"
    target_out = sys.argv[2] if len(sys.argv) > 2 else "results/summary.md"
    aggregate_results(target_dir, target_out)
